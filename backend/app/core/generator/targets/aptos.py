from typing import Dict, Any, Tuple
from app.core.graph.schema import ContractGraph
from app.core.generator.source_map import SourceMap
from app.core.generator.targets.base import Target

class AptosMoveTarget(Target):
    """Deterministic Aptos Move code generator target (PRD FR-4.1 - 4.6)."""

    def generate(self, graph: ContractGraph) -> Tuple[Dict[str, str], SourceMap]:
        source_map = SourceMap()
        package_name = graph.meta.name
        module_name = graph.meta.moduleName
        
        move_toml = f"""[package]
name = "{package_name}"
version = "{graph.meta.version}"

[dependencies]
AptosFramework = {{ git = "https://github.com/aptos-labs/aptos-framework.git", rev = "mainnet", subdir = "aptos-framework" }}
"""
        
        # Skeleton Move source
        sources = f"""module 0x1::{module_name} {{
    use std::signer;
    use std::string::String;

    // Auto-generated by Smart Contract Copilot
    // Target: Aptos Move
}}
"""
        files = {
            "Move.toml": move_toml,
            f"sources/{module_name}.move": sources
        }
        return files, source_map
